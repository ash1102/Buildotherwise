#!/usr/bin/env node
/**
 * Builds migration/supabase/seed.sql from the Base44 content export in
 * migration/content/*.json (program-owned content only: Module, Lesson,
 * LibraryResource, LessonReviewPackage, TribeThread).
 *
 * - Keeps each record's Base44 id, so lesson links and carry-forward codes still match.
 * - Drops Base44 account ids (created_by_id): content isn't owned by a participant.
 * - Admin-only fields go to public.admin_fields, never into the readable tables.
 * - Safe to run twice: existing ids are updated, not duplicated.
 *
 * Run: node migration/scripts/generate-seed.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const tables = JSON.parse(fs.readFileSync(path.join(root, 'src/api/supabaseTables.json'), 'utf8'));
const schemaSql = fs.readFileSync(path.join(root, 'migration/supabase/schema.sql'), 'utf8');
const CONTENT = ['Module', 'Lesson', 'LibraryResource', 'LessonReviewPackage', 'TribeThread'];
const SKIP = new Set(['created_by_id', 'created_by', 'is_sample', 'is_deleted', 'deleted_date', 'environment', 'app_id', 'entity_name']);

/** Column names and types per table, read from schema.sql so the seed always matches it. */
function columnsOf(table) {
  const m = schemaSql.match(new RegExp(`create table if not exists public\\.${table} \\(([\\s\\S]*?)\\n\\);`));
  const cols = {};
  for (const line of (m?.[1] || '').split('\n')) {
    const c = line.trim().match(/^"?([a-z_]+)"?\s+([a-z ]+?)(?:\s+default|\s+primary|\s+not|\s+references|,|$)/);
    if (c) cols[c[1]] = c[2].trim();
  }
  return cols;
}

const lit = (value, type) => {
  if (value === null || value === undefined) return 'null';
  if (type === 'jsonb') return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
  if (type === 'boolean') return value ? 'true' : 'false';
  if (type === 'double precision' || type === 'bigint') return Number.isFinite(Number(value)) ? String(Number(value)) : 'null';
  if (type === 'timestamptz') return `'${String(value).replace(/'/g, "''")}'::timestamptz`;
  return `'${String(value).replace(/'/g, "''")}'`;
};
const q = (name) => `"${name}"`;

const out = ['-- Generated by migration/scripts/generate-seed.mjs from the Base44 content export.', 'begin;'];
const summary = {};
for (const entity of CONTENT) {
  const file = path.join(root, 'migration/content', `${entity}.json`);
  if (!fs.existsSync(file)) { console.warn(`Missing ${file}`); continue; }
  const rows = JSON.parse(fs.readFileSync(file, 'utf8'));
  const { table, adminOnly = [] } = tables[entity];
  const cols = columnsOf(table);
  let adminCount = 0;
  for (const row of rows) {
    const names = Object.keys(row).filter((k) => !SKIP.has(k) && cols[k] && !adminOnly.includes(k));
    const values = names.map((k) => lit(row[k], cols[k]));
    const updates = names.filter((k) => k !== 'id').map((k) => `${q(k)} = excluded.${q(k)}`);
    out.push(`insert into public.${table} (${names.map(q).join(', ')}) values (${values.join(', ')}) on conflict (id) do update set ${updates.join(', ')};`);
    for (const field of adminOnly) {
      if (row[field] === null || row[field] === undefined || row[field] === '') continue;
      adminCount += 1;
      out.push(`insert into public.admin_fields (entity, record_id, field, value) values (${lit(entity)}, ${lit(row.id)}, ${lit(field)}, ${lit(typeof row[field] === 'string' ? row[field] : JSON.stringify(row[field]))}) on conflict (entity, record_id, field) do update set value = excluded.value;`);
    }
  }
  summary[entity] = { rows: rows.length, adminFields: adminCount };
}
out.push('commit;');
fs.writeFileSync(path.join(root, 'migration/supabase/seed.sql'), out.join('\n') + '\n');
console.log(JSON.stringify(summary));
