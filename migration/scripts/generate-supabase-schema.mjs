#!/usr/bin/env node
/**
 * Generates migration/supabase/schema.sql from base44/entities/*.jsonc.
 *
 * One Postgres table per Base44 entity, same field names, so the app's
 * Supabase adapter (src/api/supabaseCompat.js) maps one to one.
 * Row-level security mirrors each entity's Base44 "rls" block:
 *   created_by_id = {{user.id}}  ->  created_by_id = auth.uid()
 *   user_condition role admin    ->  public.is_admin()
 *   user_condition role user     ->  any signed-in user
 *   {} (empty)                   ->  anyone, signed in or not
 * Fields with their own admin-only rls (internal_notes, full_text_uri) go to a
 * separate admin-only table so they can't leak through `select *`.
 *
 * Run: node migration/scripts/generate-supabase-schema.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const dir = path.join(root, 'base44/entities');
const out = path.join(root, 'migration/supabase/schema.sql');

const stripComments = (text) => text.replace(/^\s*\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '');
const snake = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
const RESERVED = new Set(['order', 'user', 'type', 'source', 'value', 'kind', 'status', 'year', 'description']);
const col = (name) => (RESERVED.has(name) ? `"${name}"` : name);

function pgType(def) {
  switch (def?.type) {
    case 'number': return 'double precision';
    case 'integer': return 'bigint';
    case 'boolean': return 'boolean';
    case 'array':
    case 'object': return 'jsonb';
    default: return 'text';
  }
}

function pgDefault(def) {
  if (def?.default === undefined) return '';
  const v = def.default;
  if (typeof v === 'string') return ` default '${v.replace(/'/g, "''")}'`;
  if (typeof v === 'boolean' || typeof v === 'number') return ` default ${v}`;
  return ` default '${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
}

/** Turns one Base44 rls rule into a SQL boolean expression. */
function rule(r) {
  if (!r || Object.keys(r).length === 0) return 'true';
  if (r.$or) return '(' + r.$or.map(rule).join(' or ') + ')';
  const parts = [];
  if (r.created_by_id) parts.push('created_by_id = auth.uid()');
  if (r.user_condition?.role === 'admin') parts.push('public.is_admin()');
  if (r.user_condition?.role === 'user') parts.push('auth.uid() is not null');
  return parts.length ? parts.join(' and ') : 'false';
}

const files = fs.readdirSync(dir).filter((f) => f.endsWith('.jsonc')).sort();
const sql = [];
sql.push(`-- Generated by migration/scripts/generate-supabase-schema.mjs. Do not edit by hand.
-- Entrepalooza on Supabase: same tables and fields as the Base44 entities.

create extension if not exists pgcrypto;

-- Accounts: one profile per Supabase auth user. Role 'admin' unlocks admin rules.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  role text not null default 'user' check (role in ('user', 'admin')),
  created_date timestamptz not null default now()
);
alter table public.profiles enable row level security;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

drop policy if exists profiles_read_own on public.profiles;
create policy profiles_read_own on public.profiles for select using (id = auth.uid() or public.is_admin());
drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles for update using (id = auth.uid())
  with check (id = auth.uid() and role = (select p.role from public.profiles p where p.id = auth.uid()));

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, full_name)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name'))
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.touch_updated_date() returns trigger
language plpgsql as $$ begin new.updated_date = now(); return new; end; $$;

-- Admin-only fields (Base44 field-level rls) live here, never in the readable tables.
create table if not exists public.admin_fields (
  entity text not null,
  record_id text not null,
  field text not null,
  value text,
  primary key (entity, record_id, field)
);
alter table public.admin_fields enable row level security;
drop policy if exists admin_fields_admin on public.admin_fields;
create policy admin_fields_admin on public.admin_fields for all using (public.is_admin()) with check (public.is_admin());
`);

const manifest = {};
for (const file of files) {
  const schema = JSON.parse(stripComments(fs.readFileSync(path.join(dir, file), 'utf8')));
  const entity = schema.name || path.basename(file, '.jsonc');
  if (entity === 'User') continue; // replaced by public.profiles
  const table = snake(entity);
  const props = schema.properties || {};
  const columns = [
    `  id text primary key default replace(gen_random_uuid()::text, '-', '')`,
    `  created_date timestamptz not null default now()`,
    `  updated_date timestamptz not null default now()`,
    `  created_by_id uuid default auth.uid() references auth.users(id) on delete cascade`,
  ];
  const adminOnly = [];
  for (const [name, def] of Object.entries(props)) {
    if (['id', 'created_date', 'updated_date', 'created_by_id'].includes(name)) continue;
    if (def?.rls) { adminOnly.push(name); continue; }
    columns.push(`  ${col(name)} ${pgType(def)}${pgDefault(def)}`);
  }
  manifest[entity] = { table, adminOnly };
  const rls = schema.rls || {};
  sql.push(`\n-- ${entity}${schema.description ? ': ' + schema.description.replace(/\n/g, ' ') : ''}`);
  sql.push(`create table if not exists public.${table} (\n${columns.join(',\n')}\n);`);
  sql.push(`create index if not exists ${table}_created_by_idx on public.${table} (created_by_id);`);
  sql.push(`alter table public.${table} enable row level security;`);
  sql.push(`drop trigger if exists ${table}_touch on public.${table};`);
  sql.push(`create trigger ${table}_touch before update on public.${table} for each row execute function public.touch_updated_date();`);
  for (const [action, sqlAction] of [['read', 'select'], ['create', 'insert'], ['update', 'update'], ['delete', 'delete']]) {
    const expr = rule(rls[action]);
    const name = `${table}_${action}`;
    sql.push(`drop policy if exists ${name} on public.${table};`);
    if (sqlAction === 'insert') {
      // A new row is always stamped with its creator; the rule decides who may create.
      const who = expr.replace('created_by_id = auth.uid()', 'auth.uid() is not null');
      sql.push(`create policy ${name} on public.${table} for insert with check (${who} and (created_by_id is null or created_by_id = auth.uid()));`);
    } else if (sqlAction === 'update') {
      sql.push(`create policy ${name} on public.${table} for update using (${expr}) with check (${expr});`);
    } else {
      sql.push(`create policy ${name} on public.${table} for ${sqlAction} using (${expr});`);
    }
  }
}

sql.push(`\n-- Live updates for tribe replies.
do $$ begin
  begin alter publication supabase_realtime add table public.tribe_reply; exception when others then null; end;
end $$;
`);

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, sql.join('\n') + '\n');
fs.writeFileSync(path.join(root, 'src/api/supabaseTables.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Wrote ${out} and src/api/supabaseTables.json for ${Object.keys(manifest).length} entities.`);
