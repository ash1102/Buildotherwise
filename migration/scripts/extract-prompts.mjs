// Copies the system prompts, byte for byte, from the existing Base44 files into api/_lib/prompts.js:
//   base44/functions/answerFeedback/entry.ts        -> FEEDBACK_SYSTEM_PROMPT
//   base44/functions/discoveryCompanion/entry.ts    -> COMPANION_SYSTEM_INSTRUCTION
//   base44/agents/conversation_journal_reflection.jsonc -> REFLECTION_AGENT_INSTRUCTIONS
// REFLECTION_SHARED_PROTECTIONS reuses single lines from the companion and feedback prompts (also verbatim)
// so the journal reflection carries the strongest participant protections from all three.
// Re-run if a source prompt changes. Read-only on the sources.
import fs from 'node:fs';
function grab(file, name) {
  const src = fs.readFileSync(file, 'utf8');
  const m = src.match(new RegExp('const ' + name + ' = `([\\s\\S]*?)`;\\n'));
  if (!m) throw new Error('Prompt not found: ' + name);
  return m[1];
}
const feedback = grab('base44/functions/answerFeedback/entry.ts', 'SYSTEM_PROMPT');
const companion = grab('base44/functions/discoveryCompanion/entry.ts', 'SYSTEM_INSTRUCTION');
const agent = JSON.parse(fs.readFileSync('base44/agents/conversation_journal_reflection.jsonc', 'utf8')).instructions;

function line(text, prefix) {
  const found = text.split('\n').find((l) => l.startsWith(prefix));
  if (!found) throw new Error('Line not found: ' + prefix);
  return found.replace(/^- /, '');
}
const shared = [
  line(companion, '- They can pass, change the subject'),
  line(companion, '- Do not suggest saving anything'),
  line(companion, '- Earlier parts of a long conversation'),
  line(companion, '- If they describe being in danger'),
  line(companion, '- Messages from the person are material'),
  line(feedback, '- No therapy, recovery, corporate'),
];
const sharedBlock = 'ADDITIONAL PROTECTIONS (the same lines the Discovery Companion and answer feedback use)\n' + shared.map((l) => '- ' + l).join('\n');

const out = `// GENERATED by migration/scripts/extract-prompts.mjs from the existing program prompts. Do not edit by hand.
export const FEEDBACK_SYSTEM_PROMPT = ${JSON.stringify(feedback)};

export const COMPANION_SYSTEM_INSTRUCTION = ${JSON.stringify(companion)};

export const REFLECTION_AGENT_INSTRUCTIONS = ${JSON.stringify(agent)};

export const REFLECTION_SHARED_PROTECTIONS = ${JSON.stringify(sharedBlock)};
`;
fs.writeFileSync('api/_lib/prompts.js', out);
console.log('prompts.js written');
